#ifndef MPV_INFINITY_MPVFLOW_VISIBILITY_RESOLVER_SHADER_H
#define MPV_INFINITY_MPVFLOW_VISIBILITY_RESOLVER_SHADER_H

static const char shader_visibility_resolver[] =
    "#version 450\n"
    "layout(set=0,binding=0,rgba16f) readonly uniform image2D sceneTex;\n"
    "layout(set=0,binding=1,rgba16f) readonly uniform image2D fwdTex;\n"
    "layout(set=0,binding=2,rgba16f) readonly uniform image2D backTex;\n"
    "layout(set=0,binding=3,rgba16f) readonly uniform image2D luma0Tex;\n"
    "layout(set=0,binding=4,rgba16f) readonly uniform image2D luma1Tex;\n"
    "layout(set=0,binding=5) uniform sampler2D frame0;\n"
    "layout(set=0,binding=6) uniform sampler2D frame1;\n"
    "layout(set=0,binding=7) uniform sampler2D motionWarped;\n"
    "layout(set=0,binding=8,rgba8) writeonly uniform image2D outTex;\n"
    "layout(set=0,binding=9,rgba8) writeonly uniform image2D maskTex;\n"
    "layout(push_constant) uniform FlowPush { ivec4 cfg; float timestep; } pc;\n"
    "layout(local_size_x=8,local_size_y=8) in;\n"
    "float flowGridAxis(float p,float extent,int blockSize,int gridCount){\n"
    "    if(gridCount<=1)return 0.0;\n"
    "    float lastAnchor=max(extent-float(blockSize),0.0);\n"
    "    float previousAnchor=min(float(gridCount-2)*4.0,lastAnchor);\n"
    "    float lastIndex=float(gridCount-1);\n"
    "    if(p<=previousAnchor)return clamp(p/4.0,0.0,lastIndex);\n"
    "    if(lastAnchor<=previousAnchor)return lastIndex;\n"
    "    return clamp(lastIndex-1.0+(p-previousAnchor)/(lastAnchor-previousAnchor),0.0,lastIndex);\n"
    "}\n"
    "vec4 flowImageAt(ivec2 q,int direction){return direction==0?imageLoad(fwdTex,q):imageLoad(backTex,q);}\n"
    "vec2 flowGridCoord(vec2 p){ivec2 e=imageSize(luma0Tex),g=imageSize(fwdTex);return vec2(flowGridAxis(p.x,float(e.x),4,g.x),flowGridAxis(p.y,float(e.y),4,g.y));}\n"
    "vec4 flowAt(vec2 p,int direction){\n"
    "    ivec2 gsize=imageSize(fwdTex); vec2 g=flowGridCoord(p);\n"
    "    ivec2 a=clamp(ivec2(floor(g)),ivec2(0),gsize-1),b=min(a+1,gsize-1); vec2 q=fract(g);\n"
    "    return mix(mix(flowImageAt(a,direction),flowImageAt(ivec2(b.x,a.y),direction),q.x),\n"
    "               mix(flowImageAt(ivec2(a.x,b.y),direction),flowImageAt(b,direction),q.x),q.y);\n"
    "}\n"
    "vec4 colorAt(sampler2D s,vec2 p){ivec2 z=textureSize(s,0);p=clamp(p,vec2(0),vec2(z-1));return textureLod(s,(p+0.5)/vec2(z),0.0);}\n"
    "float inBounds(vec2 p,ivec2 z){return float(p.x>=0.0&&p.y>=0.0&&p.x<=float(z.x-1)&&p.y<=float(z.y-1));}\n"
    "float rgbDiff(vec3 a,vec3 b){return (abs(a.r-b.r)+abs(a.g-b.g)+abs(a.b-b.b))/3.0;}\n"
    "float matchCost(vec2 p,vec2 dpx,float t,out float textureEnergy){\n"
    "    ivec2 z=textureSize(frame0,0);\n"
    "    vec2 s0=p-t*dpx,s1=s0+dpx;\n"
    "    if(inBounds(s0,z)<0.5||inBounds(s1,z)<0.5)return 10.0;\n"
    "    vec3 c0=colorAt(frame0,s0).rgb,c1=colorAt(frame1,s1).rgb;\n"
    "    float err=0.0,norm=0.0,energy=0.0;\n"
    "    for(int y=-2;y<=2;y++)for(int x=-2;x<=2;x++){\n"
    "        vec2 o=vec2(x,y);float r2=float(x*x+y*y);\n"
    "        vec3 a=colorAt(frame0,s0+o).rgb,b=colorAt(frame1,s1+o).rgb;\n"
    "        float bilateral=exp(-5.0*max(rgbDiff(a,c0),rgbDiff(b,c1)));\n"
    "        float w=(r2==0.0?4.0:1.0/(1.0+0.20*r2))*bilateral;\n"
    "        err+=w*rgbDiff(a,b); norm+=w;\n"
    "        energy+=w*(rgbDiff(a,c0)+rgbDiff(b,c1))*0.5;\n"
    "    }\n"
    "    textureEnergy=energy/max(norm,0.0001);\n"
    "    return err/max(norm,0.0001);\n"
    "}\n"
    "void main(){\n"
    "    ivec2 p=ivec2(gl_GlobalInvocationID.xy),outSize=pc.cfg.xy,motionSize=pc.cfg.zw;\n"
    "    if(any(greaterThanEqual(p,outSize)))return;\n"
    "    vec4 fallback=texelFetch(motionWarped,p,0);\n"
    "    if(imageLoad(sceneTex,ivec2(0)).r>0.1882353){\n"
    "        if(pc.timestep<0.0)imageStore(outTex,p,vec4(0.0,0.0,0.0,1.0));\n"
    "        else imageStore(outTex,p,fallback);\n"
    "        imageStore(maskTex,p,vec4(0));return;\n"
    "    }\n"
    "    // A pair-wide abstention must not be split back into warped islands.\n"
    "    if(imageLoad(sceneTex,ivec2(0)).g>0.5){\n"
    "        if(pc.timestep<0.0)imageStore(outTex,p,vec4(0.0,0.0,0.0,1.0));\n"
    "        else imageStore(outTex,p,fallback);\n"
    "        imageStore(maskTex,p,vec4(0));return;\n"
    "    }\n"
    "    float t=pc.timestep<0.0?0.5:clamp(pc.timestep,0.0,1.0);\n"
    "    vec2 flowP=(vec2(p)+0.5)*vec2(motionSize)/vec2(outSize)-vec2(0.5);\n"
    "    vec2 scale=vec2(outSize)/vec2(motionSize);\n"
    "    vec4 f=flowAt(flowP,0),b=flowAt(flowP,1);\n"
    "    vec2 d0=f.xy*scale,d1=-b.xy*scale;\n"
    "    float e0=0.0,e1=0.0;float c0=matchCost(vec2(p),d0,t,e0),c1=matchCost(vec2(p),d1,t,e1);\n"
    "    float baselineCost=min(c0,c1);\n"
    "    vec2 g=flowGridCoord(flowP);ivec2 gs=imageSize(fwdTex);\n"
    "    ivec2 a=clamp(ivec2(floor(g)),ivec2(0),gs-1),q=min(a+1,gs-1);\n"
    "    vec2 hypotheses[8];float costs[8];float energies[8];\n"
    "    hypotheses[0]=imageLoad(fwdTex,a).xy*scale;\n"
    "    hypotheses[1]=imageLoad(fwdTex,ivec2(q.x,a.y)).xy*scale;\n"
    "    hypotheses[2]=imageLoad(fwdTex,ivec2(a.x,q.y)).xy*scale;\n"
    "    hypotheses[3]=imageLoad(fwdTex,q).xy*scale;\n"
    "    hypotheses[4]=-imageLoad(backTex,a).xy*scale;\n"
    "    hypotheses[5]=-imageLoad(backTex,ivec2(q.x,a.y)).xy*scale;\n"
    "    hypotheses[6]=-imageLoad(backTex,ivec2(a.x,q.y)).xy*scale;\n"
    "    hypotheses[7]=-imageLoad(backTex,q).xy*scale;\n"
    "    float best=10.0,second=10.0,bestEnergy=0.0;vec2 bestD=d0;\n"
    "    for(int i=0;i<8;i++){\n"
    "        float energy=0.0;float cost=matchCost(vec2(p),hypotheses[i],t,energy);\n"
    "        costs[i]=cost;energies[i]=energy;\n"
    "        if(cost<best){best=cost;bestD=hypotheses[i];bestEnergy=energy;}\n"
    "    }\n"
    "    // Compare only genuinely different motion clusters; duplicate grid nodes do not\n"
    "    // masquerade as independent evidence for/against a layer hypothesis.\n"
    "    for(int i=0;i<8;i++)if(length(hypotheses[i]-bestD)>4.0)second=min(second,costs[i]);\n"
    "    float margin=second-best;\n"
    "    float baselineDistance=min(length(bestD-d0),length(bestD-d1));\n"
    "    vec2 candidateS0=vec2(p)-t*bestD,candidateS1=candidateS0+bestD;\n"
    "    float centerError=rgbDiff(colorAt(frame0,candidateS0).rgb,colorAt(frame1,candidateS1).rgb);\n"
    "    bool forwardSupport=false,backwardSupport=false;\n"
    "    for(int i=0;i<4;i++){\n"
    "        if(length(hypotheses[i]-bestD)<=4.0&&costs[i]<=best+0.05)forwardSupport=true;\n"
    "        if(length(hypotheses[i+4]-bestD)<=4.0&&costs[i+4]<=best+0.05)backwardSupport=true;\n"
    "    }\n"
    "    bool uniquelySupported=bestEnergy>0.012&&margin>max(0.025,best*0.30)&&centerError<0.04&&forwardSupport&&backwardSupport;\n"
    "    bool evidence=uniquelySupported&&baselineCost-best>0.035&&baselineDistance>3.0;\n"
    "    vec4 result=fallback;\n"
    "    if(evidence){\n"
    "        vec2 s0=vec2(p)-t*bestD,s1=s0+bestD;\n"
    "        vec4 ca=colorAt(frame0,s0),cb=colorAt(frame1,s1);\n"
    "        result=mix(fallback,mix(ca,cb,t),0.25);\n"
    "    }\n"
    "    result.a=1.0;\n"
    "    float supported=evidence?1.0:0.0;\n"
    "    if(pc.timestep<0.0){\n"
    "        imageStore(outTex,p,vec4(supported,supported,supported,1.0));\n"
    "        imageStore(maskTex,p,vec4(supported,0.0,0.0,supported));\n"
    "        return;\n"
    "    }\n"
    "    imageStore(outTex,p,result);\n"
    "    imageStore(maskTex,p,vec4(supported,clamp(best,0.0,1.0),clamp(margin,0.0,1.0),supported));\n"
    "}\n"
;

#endif /* MPV_INFINITY_MPVFLOW_VISIBILITY_RESOLVER_SHADER_H */
